fn main() {
    let manifest =
        std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    notices(&manifest);
    content(&manifest);
    tauri_build::build()
}

/// resources/content.db, built from the repository's content/ with ka-pack: structural
/// validation only (review A5); `ka-pack validate --run` judges content separately.
fn content(manifest: &std::path::Path) {
    let root = manifest.join("../../../content");
    println!("cargo:rerun-if-changed={}", root.display());
    let registry = ka_core::registry();
    let data = match ka_pack::build_content(&root, &registry) {
        Ok(d) => d,
        Err(issues) => {
            let list: Vec<String> = issues.iter().map(|i| format!("  {i}")).collect();
            panic!(
                "content/ is invalid (run `cargo run -p ka-pack -- validate`):
{}",
                list.join(
                    "
"
                )
            );
        }
    };
    let out = manifest.join("resources/content.db");
    ka_pack::write_db(&out, &data).expect("write resources/content.db");
}

/// The first line of the placeholder notices file.
const NOTICES_PLACEHOLDER: &str = "KATABOX_ARCH_NOTICES_PLACEHOLDER";

/// THIRD_PARTY_NOTICES.txt is a bundled resource generated by `pnpm notices`.
/// Development builds get a placeholder; a release build refuses to ship one.
fn notices(manifest: &std::path::Path) {
    let path = manifest.join("resources/THIRD_PARTY_NOTICES.txt");
    println!("cargo:rerun-if-changed={}", path.display());
    println!("cargo:rerun-if-env-changed=KATABOX_ALLOW_PLACEHOLDER_NOTICES");
    let placeholder = std::fs::read_to_string(&path)
        .map(|s| s.starts_with(NOTICES_PLACEHOLDER))
        .unwrap_or(true);
    if !placeholder {
        return;
    }
    let release = std::env::var("PROFILE").as_deref() == Ok("release");
    if release && std::env::var_os("KATABOX_ALLOW_PLACEHOLDER_NOTICES").is_none() {
        panic!(
            "{} is missing or a placeholder: run `pnpm notices` before a release build",
            path.display()
        );
    }
    if !path.exists() {
        std::fs::create_dir_all(path.parent().expect("resources folder"))
            .expect("create resources/");
        std::fs::write(
            &path,
            format!(
                "{NOTICES_PLACEHOLDER}\nRun `pnpm notices` to generate the third-party notices.\n"
            ),
        )
        .expect("write the placeholder notices");
    }
}
